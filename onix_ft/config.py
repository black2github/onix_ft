"""
Конфигурация OnixFT — все пользовательские настройки в одном месте.

Этот файл редактируется один раз при установке и не требует изменений
при обновлении остальных скриптов.
Текущие параметры дают скорость около 3,6 МБ/час

Параметры сгруппированы по влиянию на скорость передачи:
  [СКОРОСТЬ]   — прямо влияют на интегральную скорость передачи
  [НАДЁЖНОСТЬ] — влияют на устойчивость при сбоях
  [UI]         — таймауты браузерной автоматизации
"""

# ==============================================================================
#  БРАУЗЕР
# ==============================================================================

# Путь к chromedriver.exe / msedgedriver.exe.
# Драйвер ищется в таком порядке: этот путь → автозагрузка
# (USE_WEBDRIVER_MANAGER) → Selenium Manager. Первые два требуют интернета,
# поэтому В ЗАКРЫТОМ КОНТУРЕ ЭТОТ ПУТЬ ОБЯЗАТЕЛЕН.
# Поддерживаются переменные окружения: r"%ProgramData%\onix\chromedriver.exe".
# CHROMEDRIVER_PATH: str = r"C:\onix\chromedriver-win64\chromedriver.exe"
CHROMEDRIVER_PATH: str = ""

# Использовать Edge вместо Chrome?
USE_EDGE: bool = False

# Автоматически скачивать chromedriver через webdriver-manager.
# Удобно на Mac/Linux где версия chromedriver может не совпадать с Chrome,
# или когда не хочется вручную следить за версией драйвера.
# Требует: pip install webdriver-manager + доступ в интернет при первом запуске.
# Флаг игнорируется, если задан CHROMEDRIVER_PATH; если автозагрузка недоступна,
# запуск не падает — драйвер ищет Selenium Manager (тоже нужен интернет).
# USE_WEBDRIVER_MANAGER: bool = False
USE_WEBDRIVER_MANAGER: bool = True

# Путь к профилю браузера — чтобы не вводить логин при каждом запуске.
# Значение разворачивает переменные окружения, поэтому НЕ ПИШИТЕ здесь свой
# логин: путь с чужим именем пользователя ломает запуск у всех остальных
# (Chrome не может создать профиль в чужой папке и молча висит до таймаута).
# Оставьте "" — потребуется ручной логин при каждом запуске.
# На VDI с перенаправленным (сетевым) AppData надёжнее локальный каталог,
# например r"C:\onix\profile-onixft".
# BROWSER_PROFILE_DIR: str = ""
BROWSER_PROFILE_DIR: str = r"%LOCALAPPDATA%\Google\Chrome\OnixFT"

# Открывать Onix отдельным окном приложения (ключ Chrome --app).
# Нужно там, где доменная политика подставляет свою стартовую страницу
# (корпоративный портал): она забирает вкладку автоматизации, сессия
# браузера не создаётся, и переход на ONIX_CHAT_URL не происходит — браузер
# при этом выглядит работающим. В режиме окна приложения браузер стартует
# сразу на нужном адресе, минуя стартовые страницы профиля и политики.
OPEN_IN_APP_WINDOW: bool = False

# Журнал chromedriver для диагностики запуска ("" — выключен).
# Включайте, когда браузер не поднимается: в журнале видно, какой именно
# исполняемый файл драйвер зовёт и чем это заканчивается.
# DRIVER_LOG_PATH: str = r"%TEMP%\onixft-chromedriver.log"
DRIVER_LOG_PATH: str = ""

# ==============================================================================
#  ONIX
# ==============================================================================

# URL чата Onix, через который выполняется передача файлов.
# Откройте нужный чат в браузере и скопируйте URL из адресной строки.
ONIX_CHAT_URL: str = "https://webexp.msg.gpb.ru/#/"

# Название чата в списке чатов — используется для очистки истории.
# Укажите точно так, как отображается в интерфейсе Onix.
ONIX_CHAT_NAME: str = "Сохраненные сообщения"

# ==============================================================================
#  ПРОТОКОЛ — влияют на скорость передачи [СКОРОСТЬ]
# ==============================================================================

# Размер одного блока данных в байтах.
# Увеличение → больше данных за одну отправку, но ближе к лимиту сообщения.
# Уменьшение → надёжнее, но медленнее.
# Текущее значение рассчитано под лимит Onix 4095 символов с XOR+base64.
# Не изменяйте без пересчёта (см. protocol.py).
CHUNK_BYTES: int = 3027

# Лимит символов в одном сообщении Onix (измерено экспериментально).
# Используется для проверки размера кадра при encode().
# Не изменяйте без проверки реального лимита мессенджера.
MESSAGE_MAX_LEN: int = 4095

# Размер окна — количество блоков, которые отправитель шлёт подряд
# не дожидаясь подтверждения. Получатель шлёт ACK раз в WINDOW_SIZE блоков.
# [СКОРОСТЬ] Увеличение ускоряет передачу, уменьшение повышает надёжность.
#   1  — классический stop-and-wait (максимальная надёжность)
#   5  — рекомендуемый старт (~2x ускорение)
#   10 — агрессивный режим (~3x ускорение)
WINDOW_SIZE: int = 10

# ==============================================================================
#  ТАЙМАУТЫ ОТПРАВКИ [СКОРОСТЬ + НАДЁЖНОСТЬ]
# ==============================================================================

# Задержка после нажатия «Отправить» перед следующим действием (секунды).
# [СКОРОСТЬ] Уменьшение ускоряет передачу, но Onix может не успеть
# обработать сообщение. Рекомендуемый диапазон: 0.5 — 1.5
SEND_DELAY: float = 1.0

# Как часто (секунды) скрипты проверяют наличие новых сообщений в чате.
# [СКОРОСТЬ] Уменьшение сокращает задержку получения ACK, но увеличивает
# нагрузку на браузер. Рекомендуемый диапазон: 0.2 — 2.0
# Значения ниже 0.2 нецелесообразны — браузер не успевает обновить DOM.
POLL_INTERVAL: float = 0.5

# Сколько раз повторить передачу окна при NACK или таймауте.
# [НАДЁЖНОСТЬ] Увеличение повышает устойчивость на нестабильном канале.
MAX_RETRIES: int = 5

# Секунд ждать ACK на всё окно блоков.
# [НАДЁЖНОСТЬ] Должен быть больше чем WINDOW_SIZE × SEND_DELAY + время
# распаковки архива на стороне получателя для последнего блока.
ACK_TIMEOUT: float = 120.0

# Секунд ждать META от отправителя при старте получателя.
# [НАДЁЖНОСТЬ] Даёт время запустить отправителя после получателя.
META_WAIT_TIMEOUT: float = 3600.0

# Секунд ждать очередной блок данных.
# [НАДЁЖНОСТЬ] При превышении получатель отправляет ABORT.
BLOCK_WAIT_TIMEOUT: float = 120.0

# ==============================================================================
#  ТАЙМАУТЫ БРАУЗЕРА [UI]
# ==============================================================================

# Ожидание появления элементов на странице (секунды).
ELEMENT_WAIT_TIMEOUT: float = 15.0

# Ожидание кнопки «Отправить» после вставки текста (секунды).
# Slate.js обновляет состояние кнопки асинхронно (~200-500 мс).
SEND_BTN_TIMEOUT: float = 2.0

# Ожидание готовности страницы при старте, включая время ручного логина.
PAGE_READY_TIMEOUT: float = 120.0

# Пауза после загрузки страницы для завершения lazy-loading истории чата.
# За это время старые сообщения появятся в DOM и будут помечены как виденные.
HISTORY_SETTLE_TIME: float = 4.0

# ==============================================================================
#  ОЧИСТКА ЧАТА
# ==============================================================================

# Очищать чат каждые N успешно переданных блоков.
# 0 — не очищать автоматически в процессе передачи.
# Рекомендуемое значение: 10 (каждые ~30 КБ исходных данных).
CLEAR_CHAT_EVERY_N_BLOCKS: int = 30

# ==============================================================================
#  ЗАКРЫТИЕ ЗАГОЛОВКОВ КАДРОВ
# ==============================================================================

# XOR-преобразование заголовков кадров протокола.
# Применяется к заголовку ПЕРЕД base64-кодированием — без знания параметра
# декодированный base64 даёт бессмысленный набор байт.
# Установите одинаковый параметр на обеих сторонах (отправитель и получатель).
# Пустая строка "" — преобразование отключено.
FRAME_KEY: str = "Papa-2026"